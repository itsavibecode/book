// Runs after both Vite builds:
//  1. copies the single-file build to book/photochop/photochop.html
//  2. writes book/photochop/sw.js, a versioned app-shell cache (precache list = index.html + assets/*)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '..', '..'); // book/photochop

// Read APP_VERSION from the one constants file without needing a TS loader.
const constants = fs.readFileSync(path.resolve(here, '..', 'src', 'app', 'constants.ts'), 'utf8');
const APP_VERSION = /APP_VERSION\s*=\s*'([^']+)'/.exec(constants)?.[1];
if (!APP_VERSION) throw new Error('APP_VERSION not found in src/app/constants.ts');

const single = path.resolve(here, '..', 'dist-single', 'index.html');
if (fs.existsSync(single)) {
  fs.copyFileSync(single, path.join(out, 'photochop.html'));
  console.log('wrote photochop.html');
}

const assetsDir = path.join(out, 'assets');
const assets = fs.existsSync(assetsDir) ? fs.readdirSync(assetsDir).map((f) => `/photochop/assets/${f}`) : [];
const precache = ['/photochop/', '/photochop/index.html', '/photochop/manifest.webmanifest', '/photochop/favicon.svg', ...assets];

// The cache name carries a hash of the precache list, so a rebuild of the same version still
// gets a fresh cache and the old one is purged on activate.
const buildHash = crypto.createHash('sha1').update(precache.join('|')).digest('hex').slice(0, 8);
const sw = [
  '// PhotoChop service worker, generated by app/scripts/postbuild.mjs. Do not edit by hand.',
  `const CACHE = 'photochop-${APP_VERSION}-${buildHash}';`,
  `const PRECACHE = ${JSON.stringify(precache, null, 2)};`,
  "self.addEventListener('install', (e) => {",
  '  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));',
  '});',
  "self.addEventListener('activate', (e) => {",
  '  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));',
  '});',
  "self.addEventListener('fetch', (e) => {",
  '  const url = new URL(e.request.url);',
  "  if (e.request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith('/photochop/')) return;",
  '  const put = (r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); return r; };',
  "  if (url.pathname.startsWith('/photochop/assets/')) {",
  '    e.respondWith(caches.match(e.request).then((hit) => hit || fetch(e.request).then(put)));',
  '    return;',
  '  }',
  "  e.respondWith(fetch(e.request).then(put).catch(() => caches.match(e.request).then((hit) => hit || caches.match('/photochop/index.html'))));",
  '});',
  '',
].join('\n');
fs.writeFileSync(path.join(out, 'sw.js'), sw);
console.log('wrote sw.js with', precache.length, 'precached files');
